/**
 * Downloads the web fonts the site uses and writes them, plus their @font-face
 * rules, into the repo so the browser never touches fonts.googleapis.com.
 *
 * The Google Fonts stylesheet is render-blocking *and* cross-origin: the
 * browser has to resolve DNS, negotiate TLS and fetch 1KB of CSS before it may
 * paint, then do it again against fonts.gstatic.com for the files themselves.
 * Lighthouse measured 800ms of blocking time on mobile for that round trip.
 * Served from our own origin the connection is already open and the files are
 * discoverable in the initial HTML.
 *
 * Run `node scripts/fetch-google-fonts.mjs` after changing the families or
 * weights below, then commit the generated files.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const fontsDir = path.resolve(__dirname, "../src/assets/fonts");
const cssPath = path.resolve(__dirname, "../src/styles/fonts.css");

// Latin only: the site ships French and English. Poppins' devanagari subset is
// never matched by our content, so it is dropped rather than downloaded.
const KEPT_SUBSETS = new Set(["latin", "latin-ext"]);

const GOOGLE_FONTS_URL =
  "https://fonts.googleapis.com/css2?family=Poppins:wght@300;400;500;600;700&family=Red+Hat+Display:wght@300..700&display=swap";

// A modern desktop UA makes Google serve woff2 rather than the legacy formats.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36";

const slug = (value) => value.toLowerCase().replace(/[^a-z0-9]+/g, "-");

const css = await fetch(GOOGLE_FONTS_URL, { headers: { "User-Agent": UA } }).then(
  (response) => {
    if (!response.ok) throw new Error(`Google Fonts responded ${response.status}`);
    return response.text();
  }
);

// Each face is preceded by a `/* subset */` comment, which is the only place
// the subset name appears — the rule itself only carries the unicode-range.
const faces = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{(.*?)\}/gs)]
  .map(([, subset, body]) => ({
    subset,
    family: /font-family:\s*'([^']+)'/.exec(body)[1],
    weight: /font-weight:\s*([^;]+);/.exec(body)[1].trim(),
    style: /font-style:\s*([^;]+);/.exec(body)[1].trim(),
    unicodeRange: /unicode-range:\s*([^;]+);/.exec(body)[1].trim(),
    url: /url\((https[^)]+)\)/.exec(body)[1],
  }))
  .filter((face) => KEPT_SUBSETS.has(face.subset));

fs.rmSync(fontsDir, { recursive: true, force: true });
fs.mkdirSync(fontsDir, { recursive: true });

const rules = [];

for (const face of faces) {
  const filename = `${slug(face.family)}-${slug(face.weight)}-${face.subset}.woff2`;
  const buffer = Buffer.from(
    await fetch(face.url, { headers: { "User-Agent": UA } }).then((r) => r.arrayBuffer())
  );
  fs.writeFileSync(path.join(fontsDir, filename), buffer);

  rules.push(
    `/* ${face.family} ${face.weight} — ${face.subset} */
@font-face {
  font-family: '${face.family}';
  font-style: ${face.style};
  font-weight: ${face.weight};
  font-display: swap;
  src: url('../assets/fonts/${filename}') format('woff2');
  unicode-range: ${face.unicodeRange};
}`
  );

  console.log(`${filename} — ${(buffer.length / 1024).toFixed(1)} KB`);
}

fs.writeFileSync(
  cssPath,
  `/* Generated by scripts/fetch-google-fonts.mjs — do not edit by hand. */\n\n${rules.join(
    "\n\n"
  )}\n`,
  "utf8"
);

console.log(`\n${faces.length} faces -> ${path.relative(process.cwd(), cssPath)}`);
